// Exercise the production event handlers with fake WebRTC messages; no microphone or paid API.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const nodes=new Map();
const node=()=>({textContent:'',value:'',className:'',style:{},classList:{add(){},remove(){},toggle(){}},replaceChildren(){},append(){},querySelector(){return node();},querySelectorAll(){return[];},disabled:false});
const document={getElementById(id){if(!nodes.has(id))nodes.set(id,node());return nodes.get(id);},createElement(){return node();},querySelectorAll(){return[];}};
const sent=[];
const timers=new Map();let timerId=0;
const fakeTimeout=(fn,ms)=>{const id=++timerId;timers.set(id,{fn,ms});return id;};
const fakeClear=id=>timers.delete(id);
const context=vm.createContext({document,console,URL,crypto:globalThis.crypto,fetch(){throw new Error('Network access is not part of this test.');},setTimeout:fakeTimeout,clearTimeout:fakeClear,setInterval,Map,JSON,Promise,window:{scrollTo(){}},sent});
let source=fs.readFileSync('web/app.js','utf8');
source=source.slice(0,source.indexOf("$('backLibrary').onclick"));
vm.runInContext(source,context);
await vm.runInContext(`(async()=>{
 doc={id:'test',title:'Torah Or',study_language:'es',pages:[{}],units:[{id:'one',title:'Uno',hebrew:'אב גד',translation:'Traducción española',translation_en:'English translation',explanation:'Explicación',explanation_en:'Explanation',source_notes:'',questions:[],sources:[],location:{start:{page:1,column:'right',line:7},end:{page:1,column:'right',line:8}}}],current_unit:0,completed:[],location:{page:1,column:'right',line:7},cursor:{unit_id:'one',phase:'hebrew'}};
 request=async(url,data)=>{if(url==='/api/cursor'){doc.cursor={unit_id:data.unit_id,phase:data.phase,interrupted:data.interrupted};return doc;}if(url==='/api/call-context')return{instructions:'Torah Or only'};throw new Error('Unexpected request: '+url);};
 connected=true;channel={readyState:'open',send(raw){sent.push(JSON.parse(raw));}};callGeneration=1;lessonFlow=true;
 await speakPhase('hebrew');
})()`,context);
const flush=()=>new Promise(resolve=>setImmediate(resolve));
const event=async e=>{context.event=e;await vm.runInContext('handleCallEvent(event,1)',context);await flush();};
assert.equal(vm.runInContext('doc.cursor.phase',context),'hebrew');
await event({type:'response.created',response:{id:'he'}});
await event({type:'response.done',response:{id:'he',status:'completed'}});
assert.equal(vm.runInContext('doc.cursor.phase',context),'hebrew','generation completion is not audio playback completion');
await event({type:'output_audio_buffer.stopped'});
assert.equal(vm.runInContext('doc.cursor.phase',context),'translation');
await event({type:'response.created',response:{id:'es'}});
await event({type:'input_audio_buffer.speech_started'});
assert.equal(vm.runInContext('lessonFlow',context),false);
assert.equal(vm.runInContext('doc.cursor.phase',context),'translation');
await event({type:'response.done',response:{id:'es',status:'cancelled'}});
await event({type:'output_audio_buffer.stopped'});
await event({type:'input_audio_buffer.speech_stopped'});
await event({type:'response.created',response:{id:'question-answer'}});
await event({type:'response.done',response:{id:'question-answer',status:'completed'}});
await event({type:'output_audio_buffer.stopped'});
assert.equal(vm.runInContext('doc.cursor.phase',context),'translation','a question must not advance the checkpoint');
assert.equal(timers.size,1,'answer playback schedules exactly one continuation');
const scheduled=[...timers.values()][0];assert.equal(scheduled.ms,4000);timers.clear();await scheduled.fn();await flush();
assert.match(sent.filter(x=>x.type==='response.create').at(-1).response.instructions,/Seguimos/);
assert.equal(vm.runInContext('doc.cursor.phase',context),'translation','resume repeats the interrupted stage');
await event({type:'response.created',response:{id:'es-resumed'}});
await event({type:'response.done',response:{id:'es-resumed',status:'completed'}});
await event({type:'output_audio_buffer.stopped'});
assert.equal(vm.runInContext('doc.cursor.phase',context),'explanation');
await event({type:'response.created',response:{id:'explain'}});
await event({type:'response.done',response:{id:'explain',status:'completed'}});
await event({type:'output_audio_buffer.stopped'});
assert.equal(vm.runInContext('doc.cursor.phase',context),'pause');
await event({type:'response.created',response:{id:'pause'}});
await event({type:'response.done',response:{id:'pause',status:'completed'}});
await event({type:'output_audio_buffer.stopped'});
assert.equal(vm.runInContext('lessonFlow',context),false,'end of concept leaves a short question window');
assert.equal(timers.size,1,'concept pause schedules continuation');
await event({type:'input_audio_buffer.speech_started'});
assert.equal(timers.size,0,'new question cancels continuation');
await event({type:'input_audio_buffer.speech_stopped'});
await event({type:'response.created',response:{id:'another-answer'}});
await event({type:'response.done',response:{id:'another-answer',status:'completed'}});
assert.equal(timers.size,0,'wait for audible answer before starting countdown');
await event({type:'output_audio_buffer.stopped'});
assert.equal(timers.size,1);
await vm.runInContext('pauseGuided()',context);
assert.equal(timers.size,0,'explicit pause cancels timer');
await event({type:'response.created',response:{id:'paused-answer'}});
await event({type:'response.done',response:{id:'paused-answer',status:'completed'}});
await event({type:'output_audio_buffer.stopped'});
assert.equal(timers.size,0,'answering during explicit pause must not resume');
await vm.runInContext("doc.study_language='en';lessonFlow=true;speakPhase('translation')",context);
const last=sent.filter(x=>x.type==='response.create').at(-1);
assert.match(last.response.instructions,/English translation/);
assert.doesNotMatch(last.response.instructions,/Traducción española/);
console.log('Voice event simulation passed: automatic resume, renewed questions, explicit pause, playback gating, interruption, question, resume, conceptual pause and language separation.');
